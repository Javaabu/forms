// Copies the lucide icons the components use into resources/icons/icons.php.
// Run with `pnpm icons` after changing the list below.
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, join } from "node:path"

const icons = [
  "arrow-down",
  "arrow-up",
  "arrow-up-down",
  "calendar",
  "check",
  "chevron-down",
  "chevron-left",
  "chevron-right",
  "chevron-up",
  "circle-alert",
  "circle-check",
  "circle-x",
  "clock",
  "download",
  "ellipsis",
  "external-link",
  "eye",
  "file",
  "file-text",
  "image",
  "info",
  "loader-circle",
  "map-pin",
  "pencil",
  "plus",
  "search",
  "trash-2",
  "triangle-alert",
  "upload",
  "x",
]

const require = createRequire(import.meta.url)
const root = join(dirname(require.resolve("lucide-static/package.json")), "icons")
const { version } = require("lucide-static/package.json")

const entries = icons.map((name) => {
  const svg = readFileSync(join(root, `${name}.svg`), "utf8")
  const body = svg
    .slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>"))
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
    .join("")
    .replaceAll(" />", "/>")

  return `    '${name}' => '${body.replaceAll("'", "\\'")}',`
})

writeFileSync(
  "resources/icons/icons.php",
  `<?php

/*
 * Lucide icons (https://lucide.dev, ISC licence), v${version}.
 * Generated by scripts/icons.mjs; don't edit by hand.
 */

return [
${entries.join("\n")}
];
`,
)

console.log(`Wrote ${icons.length} icons`)
